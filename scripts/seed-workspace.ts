/**
 * Seeds a workspace at any stage, in any state that stage can be in.
 *
 * `scripts/seed-demo.ts` gets one fixed workspace to an early stage so the app
 * has something real to open onto. This generalises that: name any stage and
 * any state it can be in, and the script drives a fresh project there through
 * the same command engine a person or a build worker would use
 * (`apps/hub/src/engine.ts`'s `execute`) — never a direct row write. What
 * comes out the other end is a state the product could actually reach.
 *
 * Usage:
 *   bun scripts/seed-workspace.ts --stage 4 --state waiting_approval
 *   bun scripts/seed-workspace.ts --stage 8 --state interrupted   # parked mid-attempt
 *   bun scripts/seed-workspace.ts --list                          # every seedable combination
 *
 * Determinism: every artifact body, project policy and title is fixed text —
 * nothing timestamped or random goes into what is seeded. The project's own
 * ids are still generated by the product (`apps/hub/src/ids.ts` uses
 * `crypto.getRandomValues`, and this script does not touch that), so two runs
 * do not produce byte-identical ids — they produce the same stage, the same
 * state, the same artifacts and the same policy every time, which is what
 * "the same command twice gives the same workspace" means here. Because the
 * title is fixed per stage/state pair, a run first tombstones any project
 * already seeded under that title, so re-seeding does not pile up duplicates.
 *
 * See SEEDING.md for what can and cannot be seeded, and why.
 */
