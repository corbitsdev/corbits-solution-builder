if (targetState === "deleted") {
  const created = await createProject({ title, owner: ACTOR, policy: POLICY });
  await command("project.delete", created.projectId, {});
  console.log(`\nSeeded "${title}" (${created.projectId}) and deleted it.`);
  let refused = "";
  await projectDetail(created.projectId, ACTOR.principalId).catch((cause: unknown) => {
    refused = cause instanceof Error ? cause.message : String(cause);
  });
  console.log(`  reading it back is refused: ${refused || "(it was not refused — this is a bug)"}`);
  await host.close();
  process.exit(0);
}

const created = await createProject({ title, owner: ACTOR, policy: POLICY });
const { projectId } = created;

if (targetStage <= 6) {
  if (targetState === "backtracked") {
    // Reaching "backtracked" at N means a run one stage further was rejected
    // back to it — so this drives one stage past N, then routes back.
    await driveThroughApprovedStages(projectId, (targetStage + 1) as Stage);
    const run = await currentRun(projectId);
    await draftAndSubmit(projectId, run.id, (targetStage + 1) as 1 | 2 | 3 | 4 | 5 | 6 | 7);
    await command("stage.reject", projectId, { runId: run.id, targetStage, reason: REASON.routed });
  } else {
    await driveThroughApprovedStages(projectId, targetStage);
    const run = await currentRun(projectId);

    if (targetState === "in_progress") {
      // Already here: driveThroughApprovedStages stopped one short of targetStage.
    } else if (targetState === "waiting_approval") {
      await draftAndSubmit(projectId, run.id, targetStage as 1 | 2 | 3 | 4 | 5 | 6);
    } else if (targetState === "waiting_approval_partial_quorum") {
      if (targetStage !== 5) {
        console.error(`waiting_approval_partial_quorum only applies to stage 5`);
        process.exit(1);
      }
      const versions = await draftAndSubmit(projectId, run.id, 5);
      await command("audience.decide", projectId, {
        runId: run.id,
        audienceName: POLICY.audiences[0]!.name,
        decision: "proceed",
        versions,
      });
    } else if (targetState === "failed") {
      await command("stage.fail", projectId, { runId: run.id, reason: REASON.failed });
    } else if (targetState === "cancelled") {
      await command("stage.cancel", projectId, { runId: run.id, reason: REASON.cancelled });
    } else {
      console.error(`Unknown state "${targetState}" for stage ${targetStage}`);
      process.exit(1);
    }
  }
} else if (targetStage === 7) {
  await driveThroughApprovedStages(projectId, 7);
  const run = await currentRun(projectId);

  if (targetState === "in_progress") {
    // Already here.
  } else if (targetState === "waiting_approval") {
    await draftAndSubmit(projectId, run.id, 7);
  } else if (targetState === "failed") {
    await command("stage.fail", projectId, { runId: run.id, reason: REASON.failed });
  } else if (targetState === "cancelled") {
    await command("stage.cancel", projectId, { runId: run.id, reason: REASON.cancelled });
  } else if (targetState === "cost_approved") {
    const versions = await draftAndSubmit(projectId, run.id, 7);
    await command("cost.approve", projectId, {
      runId: run.id,
      versions,
      forecastUsd: 1800,
      assumptions: ["Seeded: within the workspace's stated cost tolerance."],
    });
  } else if (targetState === "approved_frozen") {
    await driveThroughStage7(projectId);
  } else if (targetState === "backtracked") {
    const { runId: buildRunId } = await driveThroughStage7(projectId);
    await command("build.start_attempt", projectId, { runId: buildRunId });
    await command("build.route_material_change", projectId, {
      runId: buildRunId,
      targetStage: 7,
      reason: REASON.routed,
    });
  } else {
    console.error(`Unknown state "${targetState}" for stage 7`);
    process.exit(1);
  }
} else if (targetStage === 8) {
  await driveThroughApprovedStages(projectId, 7);
  const { runId: queuedRunId } = await driveThroughStage7(projectId);

  if (targetState === "queued") {
    // Already here.
  } else {
    const started = await command("build.start_attempt", projectId, { runId: queuedRunId });
    const runningRunId = started.runId;

    if (targetState === "running") {
      // Already here.
    } else if (targetState === "waiting_human") {
      await command(
        "build.wait_for_human",
        projectId,
        { runId: runningRunId, kind: "permission", prompt: "Seeded: the build wants to install a dependency. Approve?" },
        HOST_ACTOR,
      );
    } else if (targetState === "interrupted") {
      await command("build.interrupt", projectId, { runId: runningRunId, reason: "Seeded: parked mid-attempt with a checkpoint." });
    } else if (targetState === "failed") {
      await command("build.fail", projectId, { runId: runningRunId, reason: REASON.failed });
    } else if (targetState === "cancelled") {
      await command("build.cancel", projectId, { runId: runningRunId, reason: REASON.cancelled });
    } else if (targetState === "evidence_accepted") {
      await writeDeliveredBytes(runningRunId);
      await command("build.accept_evidence", projectId, {
        runId: runningRunId,
        versions: [],
        verifierReport: await verifierReportFor(runningRunId),
        descriptors: [
          {
            category: "source",
            path: "dist/chess.app",
            sha256: DELIVERED_SHA,
            sizeBytes: DELIVERED_BYTES.byteLength,
            mediaType: "application/octet-stream",
            access: "local",
            required: true,
          },
        ],
        verification: { requiredChecks: "seeded" },
        actualCost: 12.5,
      });
    } else {
      console.error(`Unknown state "${targetState}" for stage 8`);
      process.exit(1);
    }
  }
} else if (targetStage === 9) {
  await driveThroughApprovedStages(projectId, 7);
  const { runId: queuedRunId } = await driveThroughStage7(projectId);
  const started = await command("build.start_attempt", projectId, { runId: queuedRunId });
  const runningRunId = started.runId;
  await writeDeliveredBytes(runningRunId);
  const accepted = await command("build.accept_evidence", projectId, {
    runId: runningRunId,
    versions: [],
    verifierReport: await verifierReportFor(runningRunId),
    descriptors: [
      {
        category: "source",
        path: "dist/chess.app",
        sha256: DELIVERED_SHA,
        sizeBytes: DELIVERED_BYTES.byteLength,
        mediaType: "application/octet-stream",
        access: "local",
        required: true,
      },
    ],
    verification: { requiredChecks: "seeded" },
    actualCost: 12.5,
  });
  const deliveryRunId = accepted.runId;

  if (targetState === "delivery_review") {
    // Already here.
  } else if (targetState === "delivered" || targetState === "archived") {
    await command("delivery.accept", projectId, {
      runId: deliveryRunId,
      manifestVersion: { artifactId: "-", versionId: "-", contentHash: "0".repeat(64) },
    });
    if (targetState === "archived") {
      await command("project.archive", projectId, { runId: deliveryRunId });
    }
  } else {
    console.error(`Unknown state "${targetState}" for stage 9`);
    process.exit(1);
  }
}

await report(projectId);
await host.close();
