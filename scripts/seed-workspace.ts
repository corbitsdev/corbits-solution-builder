const ACTOR: Actor = { ...localActor(), displayName: "You" };
const HOST_ACTOR: Actor = { principalId: HOST_PRINCIPAL, displayName: "Solutions Builder host" };

async function command(
  type: Command,
  projectId: string,
  payload: Record<string, unknown>,
  actor: Actor = ACTOR,
): Promise<CommandOutcome> {
  return execute({
    type,
    actor,
    projectId,
    idempotencyKey: newId.command(),
    correlationId: newId.correlation(),
    payload,
  });
}

// --- deterministic title, and tombstoning any earlier seed under it ----

const title = `Seed: stage ${targetStage} ${targetState}`;

async function retireExisting(): Promise<void> {
  const existing = await listProjects();
  for (const project of existing.filter((entry) => entry.title === title)) {
    try {
      await command("project.delete", project.id, {});
    } catch (cause) {
      // Already deleted, or nothing left to delete — either way the slot is free.
      if (!(cause instanceof HostError)) throw cause;
    }
  }
}
await retireExisting();

// --- driving the project through the same commands a person would -----

type Version = { artifactId: string; versionId: string; contentHash: string };

async function currentRun(projectId: string) {
  const detail = await projectDetail(projectId, ACTOR.principalId);
  if (!detail.current) throw new Error("project has no current run");
  return detail.current;
}

/** Drafts and submits every artifact stage N owns, leaving the run waiting_approval at N. */
async function draftAndSubmit(projectId: string, runId: string, stage: 1 | 2 | 3 | 4 | 5 | 6 | 7): Promise<Version[]> {
  const versions: Version[] = [];
  for (const entry of ARTIFACTS_FOR_STAGE[stage]) {
    const node = await writeArtifact(
      {
        projectId,
        kind: entry.kind,
        title: entry.title,
        content: entry.body,
        mediaType: "text/markdown",
        sourceVersionIds: [],
        provenance: { producer: "human", runId },
      },
      ACTOR,
    );
    versions.push({ artifactId: node.artifactId, versionId: node.nodeId, contentHash: node.contentHash });
  }
  await command("stage.submit", projectId, { runId, versions });
  return versions;
}

/** Records both audiences deciding "proceed" — the full stage-5 quorum. */
async function decideFullQuorum(projectId: string, runId: string, versions: Version[]): Promise<void> {
  for (const audience of POLICY.audiences) {
    await command("audience.decide", projectId, {
      runId,
      audienceName: audience.name,
      decision: "proceed",
      versions,
    });
  }
}

/** Advances stages 1-6 through approval, stage 5's quorum included, up to (not including) targetStage. */
async function driveThroughApprovedStages(projectId: string, upTo: Stage): Promise<void> {
  for (let stage = 1; stage < upTo && stage <= 6; stage += 1) {
    const run = await currentRun(projectId);
    const versions = await draftAndSubmit(projectId, run.id, stage as 1 | 2 | 3 | 4 | 5 | 6);
    if (stage === 5) await decideFullQuorum(projectId, run.id, versions);
    await command("stage.approve", projectId, { runId: run.id, versions });
  }
}

/** Drives stage 7 through cost.approve, then build.freeze, leaving a queued build run at 8. */
async function driveThroughStage7(projectId: string): Promise<{ runId: string }> {
  const run = await currentRun(projectId);
  const versions = await draftAndSubmit(projectId, run.id, 7);
  await command("cost.approve", projectId, {
    runId: run.id,
    versions,
    forecastUsd: 1800,
    assumptions: ["Seeded: within the workspace's stated cost tolerance."],
  });
  const frozen = await command("build.freeze", projectId, {
    runId: run.id,
    versions,
    placement: "local",
    targets: ["cli"],
  });
  return { runId: frozen.runId };
}

/** Writes real, fixed bytes into a build run's workspace, matching DELIVERED_SHA. */
async function writeDeliveredBytes(buildRunId: string): Promise<void> {
  const workspace = await workspaceFor(buildRunId);
  await mkdir(join(workspace, "dist"), { recursive: true });
  await writeFile(join(workspace, "dist", "chess.app"), DELIVERED_BYTES);
}

/**
 * `build.accept_evidence` requires a genuine verifier report (BUILD_PLAN_V3
 * §7), so seeding a run past it runs the same completion judge a real
 * attempt would have, against the workspace as this script left it, rather
 * than fabricating a confidence level. No plan or requirements text is
 * seeded here, so the mechanical ceiling — never an inference call — decides
 * the level, exactly as `judgeCompletion` does for any workspace with
 * nothing to interpret semantics into.
 */
async function verifierReportFor(buildRunId: string): Promise<VerifierReport> {
  const workspace = await workspaceFor(buildRunId);
  const verdict = await judgeCompletion({ workspaceRoot: workspace, plan: "", requirements: "" });
  return verifierReportOf(verdict);
}

async function report(projectId: string): Promise<void> {
  const detail = await projectDetail(projectId, ACTOR.principalId);
  console.log(`\nSeeded "${detail.project.title}" (${projectId})`);
  console.log(`  requested: stage ${targetStage}, state ${targetState}`);
  for (const run of detail.runs) {
    console.log(`  run ${run.id.slice(0, 12)}…  kind=${run.kind}  stage=${run.stage}  state=${run.state}`);
  }
  if (detail.waits.length > 0) {
    console.log(`  ${detail.waits.length} decision waiting: ${detail.waits[0]?.title ?? ""}`);
  }
  if (detail.project.archivedAt) {
    console.log(`  project archivedAt=${new Date(detail.project.archivedAt).toISOString()}`);
  }
}

