function usage(): never {
  console.log(`Usage: bun scripts/seed-workspace.ts --stage <1-9> --state <name>
       bun scripts/seed-workspace.ts --list

Seeds one project so it sits at the named stage, in the named state, with the
state that stage would actually carry: approved artifacts from every earlier
stage, recorded approvals, audience decisions where stage 5 needs them.

--list prints every stage/state combination this script can seed, and why the
ones it refuses cannot be reached.`);
  process.exit(1);
}

function arg(name: string): string | undefined {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? undefined : process.argv[index + 1];
}

